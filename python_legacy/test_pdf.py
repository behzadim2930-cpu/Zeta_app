        print(f"   حجم فایل نهایی: {file_size / 1024:.1f} کیلوبایت")
        print("\nبررسی ویژگی‌های تست:")
        print("   ✓ نام‌های طولانی بدون سرریز (Overflow) جای گرفتند.")
